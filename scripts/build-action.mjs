import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

/**
 * Bundles the GitHub Action into a single committed file.
 *
 * GitHub runs `action.yml` without installing dependencies, so the bundle must
 * be self-contained. Optional native modules are kept external because they are
 * guarded require() calls that must not break the bundle.
 */
const outfile = path.join('apps', 'github-action', 'dist', 'index.js');
await mkdir(path.dirname(outfile), { recursive: true });

await build({
  entryPoints: ['apps/github-action/src/index.ts'],
  outfile,
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  legalComments: 'none',
  sourcemap: false,
  logLevel: 'info',
  external: ['pg-native', 'pg-cloudflare', 'cloudflare:sockets'],
  banner: {
    js: '// Generated by scripts/build-action.mjs. Do not edit by hand; run "pnpm build:action".',
  },
});
